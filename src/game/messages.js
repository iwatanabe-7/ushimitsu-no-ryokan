export function ledgerEntries({ lap2 = false, lap1Name = '', signed = null } = {}) {
  const rows = [
    { date: '昭和四十七年 十月三日', room: '桔梗の間', mark: 'kikyo', name: '千代' },
    { date: '昭和四十七年 十月九日', room: '松の間', mark: null, name: '佐伯 正' },
    { date: '平成三年 八月十二日', room: '竹の間', mark: null, name: '小松 ゆり' },
    { date: '平成二十年 二月二日', room: '菖蒲の間', mark: 'shobu', name: '遠野 誠一' },
  ];
  if (lap2) rows.push({ date: '日付なし', room: '椿の間', mark: 'tsubaki', name: lap1Name || '午前二時', faded: true });
  rows.push({ date: '今宵', room: '椿の間', mark: 'tsubaki', name: signed || '', blank: !signed });
  return rows;
}
